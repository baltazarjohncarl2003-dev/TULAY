-- TULAY AI chat history for signed-in users (owner's request, 2026-11-22). Private to the account; users can delete chats.
-- Prices are never stored: a reopened chat re-matches its saved needs against live listings.

create table public.ai_chats (
  id uuid primary key, -- generated by the browser, so a retried first turn cannot create a second chat
  user_id uuid not null references public.profiles (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 80),
  turns jsonb not null default '[]' check (jsonb_typeof(turns) = 'array' and jsonb_array_length(turns) <= 20),
  needs jsonb not null default '[]' check (jsonb_typeof(needs) = 'array' and jsonb_array_length(needs) <= 20),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index ai_chats_user_idx on public.ai_chats (user_id, updated_at desc);

-- Adds turn number p_turn (from 0). A repeat of a saved turn is ignored; the title is set once, on the first turn.
create function public.save_ai_turn(
  p_id uuid,
  p_turn integer,
  p_message text,
  p_reply text,
  p_title text,
  p_needs jsonb
) returns void
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := private.require_user();
  chat public.ai_chats;
  clean_title text := left(btrim(coalesce(p_title, '')), 80);
begin
  if p_id is null or p_turn is null or p_turn < 0 or p_turn >= 20
    or char_length(coalesce(p_message, '')) not between 1 and 1000
    or char_length(coalesce(p_reply, '')) not between 1 and 1000
    or clean_title = ''
    or jsonb_typeof(p_needs) is distinct from 'array' or jsonb_array_length(p_needs) > 20
    or pg_column_size(p_needs) > 16384 then
    raise exception 'This chat could not be saved' using errcode = '22023';
  end if;

  insert into public.ai_chats (id, user_id, title) values (p_id, uid, clean_title) on conflict (id) do nothing;
  select * into chat from public.ai_chats where id = p_id for update;
  if chat.user_id <> uid then
    raise exception 'Chat not found' using errcode = 'P0002';
  end if;
  if jsonb_array_length(chat.turns) <> p_turn then
    return; -- already saved, or out of order
  end if;

  update public.ai_chats
  set turns = turns || jsonb_build_array(jsonb_build_object('message', p_message, 'reply', p_reply)),
      needs = p_needs,
      updated_at = now()
  where id = p_id;
end $$;

revoke all on public.ai_chats from anon, authenticated;
grant select, delete on public.ai_chats to authenticated;
alter table public.ai_chats enable row level security;
create policy "ai_chats: own, read" on public.ai_chats for select to authenticated
  using (user_id = (select auth.uid()));
create policy "ai_chats: own, delete" on public.ai_chats for delete to authenticated
  using (user_id = (select auth.uid()));

revoke execute on function public.save_ai_turn(uuid, integer, text, text, text, jsonb) from public, anon;
grant execute on function public.save_ai_turn(uuid, integer, text, text, text, jsonb) to authenticated;
